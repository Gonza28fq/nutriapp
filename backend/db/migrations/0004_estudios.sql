-- 0004 · Estudios del paciente
-- Registro de los estudios que se hizo el paciente (sin archivos por ahora).
-- Si es un laboratorio con valores cargados, se vincula a la fila de `laboratorios`.

CREATE TABLE IF NOT EXISTS estudios (
  id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  paciente_id       integer NOT NULL REFERENCES pacientes (id) ON DELETE CASCADE,
  consulta_id       integer REFERENCES consultas (id) ON DELETE SET NULL,
  laboratorio_id    integer REFERENCES laboratorios (id) ON DELETE SET NULL,
  tipo              text NOT NULL DEFAULT 'laboratorio'
                    CHECK (tipo IN ('laboratorio', 'imagen', 'cardiologico', 'bioimpedancia', 'densitometria', 'otro')),
  nombre            varchar(150) NOT NULL,
  fecha             date NOT NULL,
  lugar             varchar(150),
  solicitado_por    varchar(150),
  resultado_resumen text,
  creado_en         timestamptz NOT NULL DEFAULT now(),
  actualizado_en    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_estudios_paciente_fecha ON estudios (paciente_id, fecha);

DROP TRIGGER IF EXISTS trg_estudios_actualizado ON estudios;
CREATE TRIGGER trg_estudios_actualizado BEFORE UPDATE ON estudios
  FOR EACH ROW EXECUTE FUNCTION set_actualizado_en();
