CREATE TABLE IF NOT EXISTS paciente_patologias (
  id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  paciente_id       integer NOT NULL REFERENCES pacientes (id) ON DELETE CASCADE,
  patologia_id      smallint NOT NULL REFERENCES patologias (id),
  grado             varchar(30),
  fecha_diagnostico date,
  activa            boolean NOT NULL DEFAULT true,
  notas             text,
  creado_en         timestamptz NOT NULL DEFAULT now(),
  actualizado_en    timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uk_paciente_patologia UNIQUE (paciente_id, patologia_id)
);
CREATE INDEX IF NOT EXISTS idx_pp_patologia ON paciente_patologias (patologia_id, activa);

DROP TRIGGER IF EXISTS trg_paciente_patologias_actualizado ON paciente_patologias;
CREATE TRIGGER trg_paciente_patologias_actualizado BEFORE UPDATE ON paciente_patologias
  FOR EACH ROW EXECUTE FUNCTION set_actualizado_en();

CREATE OR REPLACE VIEW v_paciente_patologias AS
  -- 1) cargadas a mano
  SELECT pp.paciente_id, p.id AS patologia_id, p.codigo, p.nombre, p.sigla, p.categoria, p.color,
         pp.grado, pp.fecha_diagnostico, 'manual'::text AS origen
  FROM paciente_patologias pp
  JOIN patologias p ON p.id = pp.patologia_id
  WHERE pp.activa

  UNION ALL
  -- 2) declaradas en la historia clínica (si no fueron cargadas a mano)
  SELECT hc.paciente_id, p.id, p.codigo, p.nombre, p.sigla, p.categoria, p.color,
         NULL, NULL, 'historia_clinica'
  FROM historia_clinica hc
  CROSS JOIN LATERAL (VALUES
    ('diabetes_1',       hc.tiene_diabetes_1),
    ('diabetes_2',       hc.tiene_diabetes_2),
    ('hipertension',     hc.tiene_hipertension),
    ('dislipemia',       hc.tiene_dislipemia),
    ('hipotiroidismo',   hc.tiene_hipotiroidismo),
    ('hipertiroidismo',  hc.tiene_hipertiroidismo),
    ('celiaquia',        hc.tiene_celiaquia),
    ('enfermedad_renal', hc.tiene_enfermedad_renal),
    ('anemia',           hc.tiene_anemia),
    ('osteoporosis',     hc.tiene_osteoporosis)
  ) AS f (codigo, tiene)
  JOIN patologias p ON p.codigo = f.codigo
  WHERE f.tiene
    AND NOT EXISTS (SELECT 1 FROM paciente_patologias pp
                    WHERE pp.paciente_id = hc.paciente_id AND pp.patologia_id = p.id)

  UNION ALL
  -- 3) calculadas desde el último IMC (si sobrepeso/obesidad no fueron cargados a mano)
  SELECT u.paciente_id, p.id, p.codigo, p.nombre, p.sigla, p.categoria, p.color,
         CASE WHEN u.imc >= 40 THEN 'Grado III' WHEN u.imc >= 35 THEN 'Grado II'
              WHEN u.imc >= 30 THEN 'Grado I' END,
         u.fecha, 'imc'
  FROM (
    SELECT DISTINCT ON (m.paciente_id) m.paciente_id, m.imc, m.fecha
    FROM mediciones m
    WHERE m.imc IS NOT NULL
    ORDER BY m.paciente_id, m.fecha DESC, m.id DESC
  ) u
  JOIN patologias p ON p.codigo = CASE WHEN u.imc >= 30 THEN 'obesidad' WHEN u.imc >= 25 THEN 'sobrepeso' END
  WHERE NOT EXISTS (SELECT 1 FROM paciente_patologias pp
                    JOIN patologias px ON px.id = pp.patologia_id
                    WHERE pp.paciente_id = u.paciente_id AND px.codigo IN ('sobrepeso', 'obesidad'));
