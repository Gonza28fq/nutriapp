-- 0005 · Auditoría / traza por paciente
-- Registra quién hizo qué, sobre qué registro (entidad + id) y cuándo.
-- Si se borra un usuario o un paciente, la traza se conserva (SET NULL).

CREATE TABLE IF NOT EXISTS auditoria (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id  integer REFERENCES usuarios (id) ON DELETE SET NULL,
  usuario     varchar(100),            -- nombre al momento del cambio (por si el usuario cambia/desaparece)
  paciente_id integer REFERENCES pacientes (id) ON DELETE SET NULL,
  entidad     varchar(40) NOT NULL,    -- paciente, consulta, medicion, laboratorio, estudio, patologia, historia_clinica, anamnesis, plan
  entidad_id  integer,
  accion      text NOT NULL CHECK (accion IN ('crear', 'editar', 'borrar', 'baja', 'reactivar')),
  resumen     varchar(300),
  cambios     jsonb,                   -- campos enviados (sin datos sensibles de autenticación)
  creado_en   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_auditoria_paciente ON auditoria (paciente_id, creado_en DESC);
CREATE INDEX IF NOT EXISTS idx_auditoria_entidad  ON auditoria (entidad, entidad_id);
